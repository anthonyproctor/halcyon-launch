// Writes assets.js: every portrait and chapter art file that exists, so the engine asks only for files that are there
// (no .jpg probe that 404s before the .svg). Run after adding or removing art: node tools/asset_manifest.mjs
// tests/smoke.spec.mjs fails when assets.js is out of date.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function assetList() {
  const dirs = ["art", "art/v2", "cast", "cast/v2"];
  for (const c of fs.readdirSync(path.join(ROOT, "courses"))) for (const d of ["art", "cast"]) dirs.push(`courses/${c}/${d}`);
  const out = [];
  for (const d of dirs) { let names = []; try { names = fs.readdirSync(path.join(ROOT, d)) } catch (e) { continue }
    for (const f of names) if (/\.(jpg|jpeg|png|webp|svg)$/i.test(f) && fs.statSync(path.join(ROOT, d, f)).isFile()) out.push(`${d}/${f}`) }
  return out.sort();
}
export function assetsJs() { return `// Generated by tools/asset_manifest.mjs: the portrait and chapter art files that exist. Don't edit by hand.\nwindow.HALCYON_ASSETS=${JSON.stringify(assetList())};\n` }
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) { fs.writeFileSync(path.join(ROOT, "assets.js"), assetsJs()); console.log(assetList().length, "assets") }
